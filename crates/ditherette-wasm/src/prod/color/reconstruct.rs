use crate::prod::contract::request::WorkingSpace;

/// Reconstructs field-generated coordinates, clipping encoded RGB and rounding byte ties upward.
/// Coordinates may exceed source gamut boxes; valid field offsets remain finite through these f64 formulas.
/// Experimental byte thresholds retain the original encoder around empirically guarded transitions.
pub fn coordinates_to_rgb8(coordinates: [f64; 3], space: WorkingSpace) -> [u8; 3] {
    let linear = match space {
        WorkingSpace::LinearRgb => coordinates,
        WorkingSpace::Oklab => oklab_to_linear(coordinates),
        WorkingSpace::Oklch => oklab_to_linear(cylindrical_to_cartesian(coordinates)),
        WorkingSpace::Cielab => cielab_to_linear(coordinates),
        WorkingSpace::Cielch => cielab_to_linear(cylindrical_to_cartesian(coordinates)),
        WorkingSpace::Srgb | WorkingSpace::Ycbcr => {
            return coordinates_to_srgb(coordinates, space).map(encoded_byte);
        }
    };
    linear.map(encode_linear_byte)
}

fn encoded_byte(channel: f64) -> u8 {
    (channel.clamp(0.0, 1.0) * 255.0).round() as u8
}

fn encode_linear_byte(channel: f64) -> u8 {
    // Experimental guard, not a certified libm error bound. Keep the original
    // encoder near analytical transitions and for linear/exceptional inputs.
    const TRANSITION_GUARD: f64 = 1e-9;
    if !(0.003_130_8..1.0).contains(&channel) {
        return encoded_byte(encode_linear(channel));
    }
    let index = BYTE_TRANSITIONS.partition_point(|&threshold| threshold <= channel);
    let near_lower = index > 0 && channel - BYTE_TRANSITIONS[index - 1] <= TRANSITION_GUARD;
    let near_upper = BYTE_TRANSITIONS
        .get(index)
        .is_some_and(|&threshold| threshold - channel <= TRANSITION_GUARD);
    if near_lower || near_upper {
        encoded_byte(encode_linear(channel))
    } else {
        index as u8
    }
}

